#!/usr/bin/env python3
"""Generate RB4011 (RouterOS) IPv6 routes for tenant networks.

Tenant IPv6 is routed, not NATed: each tenant network's /64 (from the tenant
pool) is reachable via its tenant router's address on the external network.
Sunbeam has no BGP, so the RB4011 needs a static route per tenant network.

    source ../env.sh                       # admin credentials
    ./ipv6-routes.py > ipv6-routes.rsc     # review, then on the router:
    /import ipv6-routes.rsc

Run once per cloud, with that cloud's admin credentials. Idempotent per
cloud: the output first removes the routes it made before for THIS cloud
(comment prefix "cib-tenant:<cloud>:"), then adds the current set, so
importing one cloud's routes never touches the other's. Re-run whenever
tenants add or remove networks or routers.

Reads OpenStack with the admin `openstack` CLI (needs to see all projects).
The pool and cloud name default to TENANT_V6_POOL and CLOUD_NAME from
bootstrap/site.env, via ../terraform/site.auto.tfvars.json. The RB4011's
blackhole route for the lab /48 (HomeLab RB4011_v4) catches everything else.
"""

import argparse
import ipaddress
import json
import subprocess
import sys
from pathlib import Path

TFVARS = Path(__file__).resolve().parent.parent / "terraform" / "site.auto.tfvars.json"


def osc(*args: str):
    r = subprocess.run(["openstack", *args, "-f", "json"], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"openstack {' '.join(args)} failed: {r.stderr.strip()}")
    return json.loads(r.stdout)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pool", help="tenant IPv6 pool (default: tenant_ipv6_pool from site.auto.tfvars.json)")
    ap.add_argument("--cloud", help="cloud name for the route tags (default: cloud_name from site.auto.tfvars.json)")
    ap.add_argument("--external-network", default="external-network")
    args = ap.parse_args()

    site = json.loads(TFVARS.read_text()) if TFVARS.exists() else {}
    pool_s = args.pool or site.get("tenant_ipv6_pool")
    if not pool_s:
        sys.exit("No tenant IPv6 pool: pass --pool or set TENANT_V6_POOL in bootstrap/site.env")
    pool = ipaddress.IPv6Network(pool_s)
    cloud = args.cloud or site.get("cloud_name")
    if not cloud:
        sys.exit("No cloud name: pass --cloud or set CLOUD_NAME in bootstrap/site.env")
    if not all(c.isalnum() or c in "-_" for c in cloud):
        sys.exit(f"Cloud name {cloud!r}: letters, digits, - and _ only (it goes into a RouterOS regex)")
    tag = f"cib-tenant:{cloud}:"

    ext = osc("network", "show", args.external_network)
    subnets = {s["ID"]: s for s in osc("subnet", "list", "--long")}

    routes = []
    for r in osc("router", "list", "--long"):
        router = osc("router", "show", r["ID"])
        gw_info = router.get("external_gateway_info") or {}
        if isinstance(gw_info, str):  # older openstackclient returns it as a JSON string
            gw_info = json.loads(gw_info) if gw_info.strip() else {}
        if gw_info.get("network_id") != ext["id"]:
            continue  # not attached to the external network: unreachable anyway
        gw6 = [
            ip["ip_address"]
            for ip in gw_info.get("external_fixed_ips", [])
            if ipaddress.ip_address(ip["ip_address"]).version == 6
        ]
        if not gw6:
            print(f"# skip {router['name']}: no IPv6 address on {args.external_network}", file=sys.stderr)
            continue
        for port in osc("port", "list", "--router", r["ID"], "--device-owner", "network:router_interface"):
            for fip in port.get("Fixed IP Addresses", []):
                subnet = subnets.get(fip["subnet_id"])
                if not subnet:
                    continue
                cidr = ipaddress.ip_network(subnet["Subnet"])
                if cidr.version != 6:
                    continue
                if not cidr.subnet_of(pool):
                    print(f"# skip {cidr} on {router['name']}: outside tenant pool {pool}", file=sys.stderr)
                    continue
                routes.append((cidr, gw6[0], router["project_id"], router["name"]))

    print(f"# Generated by cib-undercloud/tools/ipv6-routes.py: {len(routes)} tenant IPv6 route(s) for {cloud}, pool {pool}")
    print("/ipv6 route")
    print(f'remove [find comment~"^{tag}"]')
    for cidr, gw, project, name in sorted(routes):
        print(f'add dst-address={cidr} gateway={gw} comment="{tag}{project}/{name}"')
    return 0


if __name__ == "__main__":
    sys.exit(main())
